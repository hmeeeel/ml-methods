plt.show()

"""Для наглядности сведём тестовые ошибки в таблицу (строки — скорость обучения, столбцы — число деревьев) и найдём для каждой скорости обучения число деревьев, при котором ошибка на тесте минимальна."""

mse_table = pd.DataFrame(test_mse_table, index=n_trees).T.round(0)
mse_table.index.name = 'learning_rate'
mse_table.columns.name = 'n_estimators'
display(mse_table)

best_n = mse_table.idxmin(axis=1)
best_mse = mse_table.min(axis=1)
