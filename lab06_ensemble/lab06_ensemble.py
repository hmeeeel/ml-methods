"""Посмотрим на пять лучших комбинаций параметров."""

cv_results_gb = pd.DataFrame(grid_gb.cv_results_)
cv_results_gb['mean_cv_mse'] = -cv_results_gb['mean_test_score']
cv_results_gb[['param_n_estimators', 'param_max_depth', 'param_learning_rate', 'param_subsample',
               'mean_cv_mse', 'rank_test_score']].sort_values('rank_test_score').head(5)

"""## 2.10. Повторное обучение и оценка с новыми параметрами

Обучим новую модель градиентного бустинга с найденными параметрами и сравним её качество с исходной моделью по тем же метрикам.
"""

gb_tuned = GradientBoostingRegressor(**grid_gb.best_params_, random_state=RANDOM_STATE)
