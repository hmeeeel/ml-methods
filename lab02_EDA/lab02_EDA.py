# 1. ВРЕМЯ признаки из DateTime - тренды и сезонность поступлений
df['intake_year']  = df['dt'].dt.year
df['intake_month'] = df['dt'].dt.month
df['intake_hour']  = df['dt'].dt.hour
df['is_weekend']   = (df['dt'].dt.dayofweek >= 5).astype(int)   # 1 = суббота/воскресенье

season_map = {12: 'winter', 1: 'winter', 2: 'winter',
              3: 'spring', 4: 'spring', 5: 'spring',
              6: 'summer', 7: 'summer', 8: 'summer',
              9: 'autumn', 10: 'autumn', 11: 'autumn'}
df['season'] = df['intake_month'].map(season_map)

# 2. Циклические признаки из DateTime: чтобы декабрь был "рядом" с январём, а 23:00 с 00:00
df['month_sin'] = np.sin(2 * np.pi * df['intake_month'] / 12)
df['month_cos'] = np.cos(2 * np.pi * df['intake_month'] / 12)
df['hour_sin']  = np.sin(2 * np.pi * df['intake_hour'] / 24)
df['hour_cos']  = np.cos(2 * np.pi * df['intake_hour'] / 24)

# Вспомогательная функция: оставить N самых частых значений, остальные назвать 'Other' - Сокращение категорий (подготовка к OHE)
def keep_top(series, n):
    top = series.value_counts().nlargest(n).index
    return series.where(series.isin(top), 'Other')

# Возраст из Age upon Intake - единая шкала в днях; log(1 + x) снижает асимметрию; группы infant, young, adult, senior (до 90, 730, 2920 дн. и старше)
