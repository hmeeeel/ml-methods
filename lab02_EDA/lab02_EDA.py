def parse_age(text):
    number, unit = text.split()
    unit = unit.rstrip('s')
    days_in_unit = {'day': 1, 'week': 7, 'month': 30, 'year': 365}   # допущение: месяц = 30 дней
    return int(number) * days_in_unit[unit]

