"""### 4.1. Значения 0 years

Нулевой возраст заменяется медианой среди животных того же вида, у которых возраст записан как «меньше года» (от 1 до 364 дней). Так замена согласуется со смыслом исходного значения 0 years.
0 years означает «младше года», без уточнения. Восстанавливать их нужно так, чтобы значение оставалось в интервале «меньше года» и не превращалось в одну повторяющуюся цифру.

**Почему не медиана.** Если заменить все 0 years медианой возраста «младше года» внутри вида, получится по одной цифре на вид (например, 30 дней у кошек): на гистограмме это ещё один узкий столбик, на диаграмме рассеяния - «прямая» из одинаковых значений. Это и есть «неразумная замена медианой» из замечаний


1. пропуску назначаются «доноры» - записи с известным возрастом строго младше года (от 1 до 364 дней);
2. набор отсортирован по времени, а заполнение делается внутри группы по связанным признакам (вид, состояние при поступлении, пол) методом ffill: пропуск получает возраст ближайшей по времени записи такой же группы;
3. если в группе нет доноров ни выше, ни ниже, берётся группа пошире (только вид).

Так возраст остаётся в интервале «младше года», значения разные, а зависимость от вида, состояния и пола сохраняется.
"""

#случайный донор из группы (вид, состояние, пол)
from collections import defaultdict

df['dt'] = pd.to_datetime(df['DateTime'], format='%m/%d/%Y %I:%M:%S %p')
df['sex'] = df['Sex upon Intake'].str.extract(r'(Male|Female)')[0].fillna('Unknown')

df['age_flag'] = 'ok'                                   # флаги сохраняем для отчёта
df.loc[df['age_days'] == 0, 'age_flag'] = 'zero_years'
df.loc[df['age_days'] < 0,  'age_flag'] = 'negative'

pools = {'zero_years': df['age_days'].between(1, 364),  # доноры: строго младше года
         'negative':   df['age_days'] > 0}
levels = [['Animal Type', 'Intake Condition', 'sex'],   # от узкой группы к широкой
          ['Animal Type', 'Intake Condition'],
          ['Animal Type']]
rng = np.random.default_rng(RANDOM_STATE)

def hot_deck(flag):
    res = pd.Series(np.nan, index=df.index)
    todo = df.index[df['age_flag'] == flag]
    pool = pools[flag]
    for cols in levels:
        donors = defaultdict(list)
        for k, a in zip(zip(*[df.loc[pool, c] for c in cols]), df.loc[pool, 'age_days']):
            donors[k].append(a)
        for i in todo[res[todo].isna()]:
            k = tuple(df.at[i, c] for c in cols)
            if k in donors:
                res[i] = rng.choice(donors[k])
    return res

for flag in pools:
    new = hot_deck(flag)
    df.loc[new.notna(), 'age_days'] = new[new.notna()]
    print(flag, 'заполнено:', new.notna().sum(), 'из', (df['age_flag'] == flag).sum())

assert (df['age_days'] > 0).all()

