def outlier_mask(data, cols, k):
    # True там, где значение вне [Q1 - k*IQR, Q3 + k*IQR]
    mask = pd.DataFrame(False, index=data.index, columns=cols)
    for c in cols:
        q1, q3 = data[c].quantile([0.25, 0.75])
        iqr = q3 - q1
        mask[c] = (data[c] < q1 - k * iqr) | (data[c] > q3 + k * iqr)
    return mask

