# Commented out IPython magic to ensure Python compatibility.
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.datasets import load_wine
from sklearn.preprocessing import StandardScaler


from sklearn.decomposition import PCA
from sklearn.manifold import TSNE


from sklearn.cluster import KMeans, DBSCAN, AgglomerativeClustering
from sklearn.neighbors import NearestNeighbors
from scipy.cluster.hierarchy import linkage, dendrogram


from sklearn.metrics import (silhouette_score, davies_bouldin_score,
                             homogeneity_score, completeness_score, v_measure_score)

import warnings
warnings.filterwarnings('ignore')

plt.rcParams.update({'font.size': 12})
# %matplotlib inline

wine = load_wine()


X = pd.DataFrame(wine.data, columns=wine.feature_names)


y = wine.target

print('Размер матрицы признаков:', X.shape)
X.head()

print('Всего пропусков в данных:', X.isna().sum().sum())
X.describe().T[['min', 'max', 'mean', 'std']].round(2)

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)


print('Максимальное |среднее| по признакам:', np.abs(X_scaled.mean(axis=0)).max().round(6))
print('Стандартные отклонения признаков:', X_scaled.std(axis=0).round(2))

pca = PCA(n_components=2, random_state=42)
X_pca = pca.fit_transform(X_scaled)
print('Доля дисперсии по компонентам:', pca.explained_variance_ratio_.round(3))
print('Суммарная доля дисперсии:', pca.explained_variance_ratio_.sum().round(3))


tsne = TSNE(n_components=2, perplexity=30, random_state=42)
X_tsne = tsne.fit_transform(X_scaled)

def plot_projections(labels, title, legend_title='Кластер'):
    """Рисует объекты в проекциях PCA и t-SNE, окрашивая их по меткам labels."""
    labels = np.asarray(labels)
    palette = plt.cm.tab10
    fig, axes = plt.subplots(1, 2, figsize=(14, 5.5))
    for ax, comp, name in zip(axes, (X_pca, X_tsne), ('PCA', 't-SNE')):
        for lab in np.unique(labels):
            mask = labels == lab
            if lab == -1:
                ax.scatter(comp[mask, 0], comp[mask, 1], color='black', marker='x',
                           s=40, label='шум (-1)')
            else:
                ax.scatter(comp[mask, 0], comp[mask, 1], color=palette(lab), s=45,
                           edgecolor='k', alpha=0.8, label=f'{legend_title} {lab}')
        ax.set_title(f'{title} ({name})')
        ax.set_xlabel('Компонента 1')
        ax.set_ylabel('Компонента 2')
        ax.legend()
    plt.tight_layout()
    plt.show()

plot_projections(y, 'Истинные классы вина', legend_title='Класс')

k_range = range(2, 11)
inertias, silhouettes, db_scores = [], [], []

for k in k_range:
    km = KMeans(n_clusters=k, n_init=10, random_state=42)
    km_labels = km.fit_predict(X_scaled)
    inertias.append(km.inertia_)
    silhouettes.append(silhouette_score(X_scaled, km_labels))
    db_scores.append(davies_bouldin_score(X_scaled, km_labels))

k_metrics = pd.DataFrame({'k': list(k_range), 'inertia': inertias,
                          'silhouette': silhouettes, 'davies_bouldin': db_scores}).round(3)
display(k_metrics)

fig, axes = plt.subplots(1, 3, figsize=(16, 4.5))
axes[0].plot(k_range, inertias, 'bo-')
axes[0].set_title('Метод локтя')
axes[0].set_ylabel('Внутрикластерная дисперсия')
axes[1].plot(k_range, silhouettes, 'go-')
axes[1].set_title('Коэффициент силуэта (больше — лучше)')
axes[1].set_ylabel('Силуэт')
axes[2].plot(k_range, db_scores, 'ro-')
axes[2].set_title('Индекс Дэвиса–Боулдина (меньше — лучше)')
axes[2].set_ylabel('Индекс Дэвиса–Боулдина')
for ax in axes:
    ax.set_xlabel('Число кластеров k')
    ax.grid(alpha=0.3)
plt.tight_layout()
plt.show()

Z = linkage(X_scaled, method='ward')


cut_height = (Z[-3, 2] + Z[-2, 2]) / 2

plt.figure(figsize=(12, 6))
dendrogram(Z, truncate_mode='lastp', p=20, color_threshold=cut_height)
plt.axhline(y=cut_height, color='k', linestyle='--', label='линия отсечения (3 кластера)')
plt.title('Дендрограмма (метод Уорда, 20 последних объединений)')
plt.xlabel('Объекты (в скобках — число объектов в ветви)')
plt.ylabel('Расстояние')
plt.legend()
plt.show()

print('Расстояния последних объединений:', Z[-5:, 2].round(1))

nn = NearestNeighbors(n_neighbors=5).fit(X_scaled)
distances, _ = nn.kneighbors(X_scaled)
k_dist = np.sort(distances[:, -1])

plt.figure(figsize=(8, 5))
plt.plot(k_dist)
plt.title('График k-расстояний (k = 5)')
plt.xlabel('Объекты, отсортированные по расстоянию')
plt.ylabel('Расстояние до 5-го соседа')
plt.grid(alpha=0.3)
plt.show()

rows = []
for min_samples in [3, 4, 5, 6]:
    for eps in np.round(np.arange(1.5, 3.51, 0.1), 1):
        db_labels = DBSCAN(eps=eps, min_samples=min_samples).fit_predict(X_scaled)
        n_clusters = len(set(db_labels)) - (1 if -1 in db_labels else 0)
        n_noise = int((db_labels == -1).sum())
        if n_clusters >= 2 and n_noise <= 0.25 * len(X_scaled):
            mask = db_labels != -1
            rows.append((min_samples, eps, n_clusters, n_noise,
                         silhouette_score(X_scaled[mask], db_labels[mask])))

dbscan_grid = pd.DataFrame(rows, columns=['min_samples', 'eps', 'n_clusters', 'n_noise', 'silhouette'])
dbscan_grid = dbscan_grid.sort_values('silhouette', ascending=False).round(3)
dbscan_grid.head(5)

kmeans = KMeans(n_clusters=3, n_init=10, random_state=42)
labels_kmeans = kmeans.fit_predict(X_scaled)

print('Размеры кластеров:', np.bincount(labels_kmeans))
plot_projections(labels_kmeans, 'k-means, k = 3')

for method in ['ward', 'complete', 'average', 'single']:
    agg_labels = AgglomerativeClustering(n_clusters=3, linkage=method).fit_predict(X_scaled)
    print(f'{method:9s} силуэт = {silhouette_score(X_scaled, agg_labels):.3f}, '
          f'размеры кластеров: {np.bincount(agg_labels)}')

agglo = AgglomerativeClustering(n_clusters=3, linkage='ward')
labels_agglo = agglo.fit_predict(X_scaled)

print('Размеры кластеров:', np.bincount(labels_agglo))
plot_projections(labels_agglo, 'Иерархическая кластеризация (Ward), 3 кластера')

dbscan = DBSCAN(eps=2.3, min_samples=5)
labels_dbscan = dbscan.fit_predict(X_scaled)

n_clusters_db = len(set(labels_dbscan)) - (1 if -1 in labels_dbscan else 0)
n_noise_db = int((labels_dbscan == -1).sum())
print(f'Количество кластеров: {n_clusters_db}')
print(f'Количество шумов: {n_noise_db}')

plot_projections(labels_dbscan, 'DBSCAN (eps = 2.3, min_samples = 5)')

def evaluate(name, labels):
    labels = np.asarray(labels)
    mask = labels != -1
    return {
        'Модель': name,
        'Кластеров': len(set(labels[mask])),
        'Шум': int((~mask).sum()),
        'Силуэт': silhouette_score(X_scaled[mask], labels[mask]),
        'Дэвис–Боулдин': davies_bouldin_score(X_scaled[mask], labels[mask]),
        'Гомогенность': homogeneity_score(y, labels),
        'Полнота': completeness_score(y, labels),
        'V-мера': v_measure_score(y, labels),
    }

results = pd.DataFrame([
    evaluate('k-means (k=3)', labels_kmeans),
    evaluate('Иерархическая (Ward, 3)', labels_agglo),
    evaluate('DBSCAN (eps=2.3, min_samples=5)', labels_dbscan),
]).set_index('Модель').round(3)
results

for name, labels in [('k-means', labels_kmeans),
                     ('Иерархическая (Ward)', labels_agglo),
                     ('DBSCAN', labels_dbscan)]:
    print(f'--- {name} ---')
    display(pd.crosstab(pd.Series(y, name='Класс'), pd.Series(labels, name='Кластер')))