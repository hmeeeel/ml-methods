"""## 4. Теоретическая часть: критерий информативности Джини

 Пусть $p_k$ — доля объектов класса $k$ в выборке $X$:

$$p_{k} = \frac{1}{|X|}\sum_{i\in X}[y_{i} = k].$$

**Критерий Джини** (индекс Джини):

$$H(X) = \sum_{k=1}^{K} p_{k}(1-p_{k}) = 1 - \sum_{k=1}^{K} p_{k}^{2},$$

где $K$ — количество классов в наборе данных $X$.

Минимум ($H(X)=0$) достигается, когда все объекты подвыборки относятся к одному классу (полная определённость, разбиение «идеальное»). Максимум достигается, когда классы в подвыборке представлены поровну (максимальная неопределённость). Критерий Джини можно интерпретировать как вероятность ошибки случайного классификатора, выбирающего класс объекта случайно согласно распределению классов в выборке.

Для построения дерева решений именно критерий Джини используется в данной работе (как указано в задании), в то время как в примере преподавателя для демонстрации расчётов использовалась энтропия Шеннона — они работают аналогичным образом и приводят к похожим деревьям.

## 5. Структура дерева: классы `Node` и `Leaf`

Дерево решений строится из двух типов узлов:

- **`Node`** (вершина/узел проверки) — хранит индекс признака `index`, по которому идёт сравнение, порог `t`, а также ссылки на левое (`true_branch`, условие выполняется) и правое (`false_branch`, условие не выполняется) поддеревья;
- **`Leaf`** (лист) — терминальный узел, в котором хранится обучающая подвыборка, попавшая в этот лист, и итоговый прогноз `prediction` — класс, к которому относится большинство объектов выборки в листе (согласно формуле $B=\arg\max_{c\in C} P(c\mid X_m)$ из теоретического материала).
"""

class Node:
    def __init__(self, index, t, true_branch, false_branch):
        self.index = index              # индекс признака для сравнения с порогом в этом узле
        self.t = t                       # значение порога
        self.true_branch = true_branch   # поддерево, удовлетворяющее условию [x_j <= t]
        self.false_branch = false_branch # поддерево, не удовлетворяющее условию


class Leaf:
    def __init__(self, data, labels):
        self.data = data
        self.labels = labels
        self.prediction = self.predict()

    def predict(self):
        # подсчёт количества объектов каждого класса в листе
        classes = {}
        for label in self.labels:
            if label not in classes:
                classes[label] = 0
            classes[label] += 1
        # класс с максимальным числом объектов в листе становится прогнозом
        prediction = max(classes, key=classes.get)
        return prediction

"""## 6. Пункт 1 задания — функция расчёта критерия Джини

Реализуем функцию `gini(labels)`, которая по вектору меток классов `labels` считает критерий информативности узла по формуле $H(X) = 1 - \sum_k p_k^2$.
"""

def gini(labels):
    """
    Критерий Джини.
    labels - метки классов объектов, попавших в узел
    Возвращает значение индекса Джини: H(X) = 1 - sum_k p_k^2
    """
    labels = list(labels)
    total = len(labels)

    # подсчёт количества объектов каждого класса (аналогично Leaf.predict)
    classes = {}
    for label in labels:
        classes[label] = classes.get(label, 0) + 1

    impurity = 1
    for label in classes:
        p = classes[label] / total
        impurity -= p ** 2

    return impurity

age = np.array([50, 55, 51, 48, 47])
