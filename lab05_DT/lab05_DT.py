"""## 8. Разбиение выборки в узле

Функция `split` (приведена в задании без изменений) делит выборку `data`/`labels` на две части по условию $[x_{\text{column\_index}} \le t]$ — она уже была использована выше и будет использоваться при поиске лучшего разбиения и при построении дерева.
"""

def split(data, labels, column_index, t):
    left = np.where(data[:, column_index] <= t)
    right = np.where(data[:, column_index] > t)
    true_data = data[left]
    false_data = data[right]
    true_labels = labels[left]
    false_labels = labels[right]
    return true_data, false_data, true_labels, false_labels

"""## 9. Пункт 3 задания — критерии останова (реализовано два)

 без критериев останова деревья решений склонны **переобучаться**: дерево будет расти, пока в каждом листе не останется объектов одного класса (или пока не иссякнут варианты разбиений), что приводит к идеальной подгонке под обучающую выборку, но слабому обобщению на тесте.


1. **`min_samples_leaf`** — минимальное количество объектов в листе. Разбиение, после которого хотя бы одна из подвыборок (левая или правая) содержит меньше объектов, чем задано этим параметром, считается недопустимым и не рассматривается при поиске лучшего разбиения (реализовано в `find_best_split`).
2. **`max_depth`** — максимальная глубина дерева (максимальное количество уровней с вопросами). Если при построении дерева достигнута заданная глубина, узел принудительно объявляется листом, даже если дальнейшее разбиение могло бы дать положительный прирост информации (реализовано в `build_tree`).

"""

def find_best_split(data, labels, min_samples_leaf=5):
    """
    Поиск наилучшего разбиения выборки (data, labels) по всем признакам и порогам.

    min_samples_leaf - критерий останова №1: минимальное количество объектов,
                        которое должно остаться в каждой из двух подвыборок после разбиения.
                        Разбиения, нарушающие это условие, пропускаются.
    """
    root_gini = gini(labels)

    best_gain = 0
    best_t = None
    best_index = None

    n_features = data.shape[1]

    for index in range(n_features):
        t_values = np.unique(data[:, index])

        for t in t_values:
            true_data, false_data, true_labels, false_labels = split(data, labels, index, t)

            # критерий останова №1: не рассматриваем разбиения, которые дают слишком маленький лист
            if len(true_labels) < min_samples_leaf or len(false_labels) < min_samples_leaf:
                continue

            current_gain = gain(true_labels, false_labels, root_gini)

            if current_gain > best_gain:
                best_gain, best_t, best_index = current_gain, t, index

    return best_gain, best_t, best_index

def build_tree(data, labels, depth=0, max_depth=5, min_samples_leaf=5):
    """
    Рекурсивное построение дерева решений.

    depth      - текущая глубина узла (глубина корня равна 0)
    max_depth  - критерий останова №2: максимальная глубина дерева
    min_samples_leaf - передаётся в find_best_split (критерий останова №1)
    """
    best_gain, t, index = find_best_split(data, labels, min_samples_leaf)

    # базовый случай 1: прироста нет либо не нашлось допустимого разбиения -> лист
    if best_gain == 0 or index is None:
        return Leaf(data, labels)

    # базовый случай 2 (критерий останова №2): достигнута максимальная глубина -> лист
    if depth >= max_depth:
        return Leaf(data, labels)

    true_data, false_data, true_labels, false_labels = split(data, labels, index, t)

    # рекурсивно строим два поддерева, увеличивая глубину на 1
    true_branch = build_tree(true_data, true_labels, depth + 1, max_depth, min_samples_leaf)
    false_branch = build_tree(false_data, false_labels, depth + 1, max_depth, min_samples_leaf)

    return Node(index, t, true_branch, false_branch)

"""## 10. Классификация объектов и вывод структуры дерева

Функции `classify_object` и `predict` проходят по построенному дереву от корня к листу: в каждом узле сравнивают значение нужного признака объекта с порогом `t` и спускаются либо в `true_branch` (если условие $[x_j \le t]$ выполняется), либо в `false_branch`. Дойдя до листа, возвращают хранящийся в нём прогноз.

Функция `print_tree` рекурсивно печатает структуру дерева — вопрос в каждом узле и прогноз в каждом листе — аналогично тому, как `sklearn.tree.plot_tree` визуально показывает вопросы и прогнозы дерева.
"""

def classify_object(obj, node):
    # останавливаем рекурсию, если достигли листа
    if isinstance(node, Leaf):
        return node.prediction

    if obj[node.index] <= node.t:
        return classify_object(obj, node.true_branch)
    else:
        return classify_object(obj, node.false_branch)


def predict(data, tree):
    classes = []
    for obj in data:
        prediction = classify_object(obj, tree)
        classes.append(prediction)
    return classes

def print_tree(node, spacing=''):
    # если лист - выводим прогноз
    if isinstance(node, Leaf):
        print(spacing + 'Прогноз:', node.prediction)
        return

    # выводим вопрос в узле
    print(spacing + 'Индекс', str(node.index), '<=', str(node.t))

    print(spacing + '--> True:')
    print_tree(node.true_branch, spacing + '  ')

    print(spacing + '--> False:')
    print_tree(node.false_branch, spacing + '  ')

"""## 11. Пункт 4 задания — метрика качества модели

Реализуем `accuracy_metric` — долю правильных ответов (accuracy), выраженную в процентах:

$$\text{accuracy} = \frac{\text{число верных прогнозов}}{\text{общее число объектов}} \cdot 100\%.$$
"""

def accuracy_metric(actual, predicted):
    actual = np.asarray(actual)
    predicted = np.asarray(predicted)
    correct = np.sum(actual == predicted)
    return correct / len(actual) * 100.0

"""## 12. Пункт 5 задания — обучение собственного дерева и сравнение с `sklearn`

Зададим параметры критериев останова и построим собственное дерево на обучающей выборке `(X_train, y_train)`.
"""

max_depth = 3
