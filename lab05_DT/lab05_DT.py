print(f'Точность собственного дерева на тестовой выборке:  {test_acc_custom:.2f}%')

"""Теперь обучим дерево решений из `sklearn` **с теми же критериями останова** (`criterion='gini'`, `max_depth`, `min_samples_leaf`), чтобы сравнение было корректным — у обеих моделей должны совпадать и критерий информативности, и ограничения на рост дерева."""

sk_tree = DecisionTreeClassifier(
    criterion='gini',
    max_depth=max_depth,
    min_samples_leaf=min_samples_leaf,
    random_state=1
)
sk_tree.fit(X_train, y_train)

sk_train_pred = sk_tree.predict(X_train)
sk_test_pred = sk_tree.predict(X_test)

