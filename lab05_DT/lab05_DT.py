assert abs(root_gini_check - 0.48) < 1e-9, 'Значение не совпадает с материалами лекции!'
print('Совпадает со значением gini=0.48 из примера преподавателя — функция реализована верно.')

"""## 7. Пункт 2 задания — функция расчёта прироста информации



$$Q(X_{m}, j, t) = H(X_{m}) - \frac{|X_{l}|}{|X_{m}|}H(X_{l}) - \frac{|X_{r}|}{|X_{m}|}H(X_{r}),$$

где $H$ — критерий Джини, $X_m$ — выборка в текущем узле, $X_l$ и $X_r$ — подвыборки, получившиеся после разбиения по вопросу $[x_j \le t]$. Чем выше $Q$, тем «лучше» разбиение — тем больше неопределённости (критерия Джини) оно устраняет.
"""

def gain(left_labels, right_labels, root_gini):
    """
    Прирост информации при разбиении выборки на left_labels и right_labels.
    root_gini - критерий Джини исходной (родительской) выборки
    """
    left_labels = np.asarray(left_labels)
    right_labels = np.asarray(right_labels)

    p = left_labels.shape[0] / (left_labels.shape[0] + right_labels.shape[0])  # доля объектов слева

    return root_gini - p * gini(left_labels) - (1 - p) * gini(right_labels)

