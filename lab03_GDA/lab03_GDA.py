"""## 12. Регуляризация L2

Одним из признаков переобучения - **очень большие по модулю веса, а метод борьбы с ним это регуляризация, то есть добавление к функционалу ошибки штрафа за большие веса:** `Q(w, X) + α·‖w‖² → min`, где α это коэффициент регуляризации (чем он больше, тем сильнее «задавлены» веса).
Так делает L2-регуляризация (Тихонова, Ridge): она гладкая, сжимает веса, но не обнуляет их. L1-регуляризация использует вместо квадрата сумму модулей весов `α·‖w‖₁` (расстояние по Манхэттену), она негладкая, но зато обнуляет незначимые веса, а значит, может использоваться для отбора признаков.

Реализация делается тем же градиентным спуском, что и раньше, с добавкой штрафа. Для L2 к градиенту просто прибавляется производная штрафа `2αw`.

Для L1 всё сложнее, потому что модуль не дифференцируем в нуле: обычный спуск с «производной» `α·sign(w)` не даёт точных нулей, а колеблется возле них. Поэтому после обычного градиентного шага применяется стандартная для L1 операция «мягкого порога»: каждый вес сдвигается к нулю на величину `η·α` и обнуляется, если он оказался меньше этого порога (проксимальный градиентный спуск). Сдвиг w₀ в обоих случаях не штрафуется,  штраф накладывается только на веса при признаках.
"""

def gradient_descent_reg(X, y, alpha, penalty='l2', eta=None, max_iter=20_000, eps=1e-10):
    """Градиентный спуск с регуляризацией. Минимизируется Q(w) + alpha * penalty(w).

    penalty='l2' : штраф alpha * ||w||_2^2, к градиенту добавляется слагаемое 2*alpha*w (Ridge);
    penalty='l1' : штраф alpha * ||w||_1 (Lasso). Модуль не дифференцируем в нуле, поэтому после
                   градиентного шага применяется "мягкое пороговое" преобразование (проксимальный шаг),
                   которое сдвигает вес к нулю на eta*alpha и обнуляет его, если он меньше порога.
    Сдвиг w[0] (вес при столбце единиц) не регуляризуется.
    """
    n, d = X.shape
    lam_max = np.linalg.eigvalsh(X.T @ X / n).max()
    if eta is None:
        eta = 0.5 / (lam_max + alpha) if penalty == 'l2' else 0.5 / lam_max
    w = np.zeros(d)
    status = 'max_iter'
    for k in range(1, int(max_iter) + 1):
        grad = 2 / n * X.T.dot(X.dot(w) - y)
        if penalty == 'l2':
            reg = 2 * alpha * w
            reg[0] = 0.0
            new_w = w - eta * (grad + reg)
        else:
            new_w = w - eta * grad
            shrunk = np.sign(new_w[1:]) * np.maximum(np.abs(new_w[1:]) - eta * alpha, 0.0)
            new_w = np.r_[new_w[0], shrunk]
        dist = np.linalg.norm(new_w - w, ord=2)
        w = new_w
        if dist < eps:
            status = 'converged'
            break
    return {'w': w, 'n_iter': k, 'status': status}

