def time_it(fn, repeats=3):
    """Измерение времени выполнения. Берём лучшее из нескольких запусков."""
    best = np.inf

    for _ in range(repeats):
        t0 = time.perf_counter()
        fn()
        elapsed = time.perf_counter() - t0
        best = min(best, elapsed)

    return best


